import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = resolve(root, "dist/terminal");
let html = await readFile(resolve(output, "index.html"), "utf8");
for (const match of [...html.matchAll(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/g)]) {
  const code = await readFile(resolve(output, match[1]), "utf8");
  html = html.replace(
    match[0],
    () => `<script type="module">${code.replaceAll("</script", "<\\/script")}</script>`,
  );
}
for (const match of [...html.matchAll(/<link\b[^>]*\bhref="([^"]+)"[^>]*>/g)]) {
  const css = await readFile(resolve(output, match[1]), "utf8");
  html = html.replace(match[0], () => `<style>${css}</style>`);
}
if (
  /<(?:script|link)\b[^>]*\b(?:src|href)="(?:https?:|\.\/assets\/)/.test(html) ||
  !html.includes("__COVE_NATIVE_GENERATION__")
)
  throw new Error("Terminal bundle still needs external assets or lost its generation marker");
await writeFile(
  resolve(root, "src/terminal-document.generated.ts"),
  `// Generated by scripts/bundle-terminal.mjs; do not edit.\nexport const terminalDocument = ${JSON.stringify(html)};\n`,
);
